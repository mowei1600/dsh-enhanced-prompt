#!/usr/bin/env node
/**
 * Build the browser bundle for dsh-enhanced-prompt.
 *
 * Input : client/ui.js (component template, plain script, no imports)
 * Output: client.js  (window.__ModuleLoader__.load({ id, factory }))
 *
 * The bundle is UI only. Rewriting happens in the Host: the button POSTs to the
 * plugin's private endpoint and the Host calls `ctx.llm`. Nothing from lib/ is
 * inlined, so the Host engine and the browser half cannot drift.
 *
 * Usage:
 *   node scripts/build-client.mjs           # write client.js
 *   node scripts/build-client.mjs --check   # exit 1 when client.js is stale
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const PKG = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))

function build() {
  const ui = fs.readFileSync(path.join(ROOT, 'client', 'ui.js'), 'utf8')
  const version = String(PKG.version || '0.0.0')
  if (!ui.includes('__PLUGIN_VERSION__')) throw new Error('client/ui.js lost its __PLUGIN_VERSION__ placeholder')
  if (/^\s*import\s/m.test(ui)) throw new Error('client/ui.js must stay a plain script (no import statements)')

  const header = [
    '/* Generated by scripts/build-client.mjs — do not edit by hand.',
    ` * Package: ${PKG.name} v${version}`,
    ' * Composer control-row button: reads the draft, asks the Host to rewrite it',
    ' * with the configured model, writes the result back into the draft. */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(PKG.name)},`,
    '  factory: (require) => {',
    "    const React = require('react');",
  ].join('\n')

  const body = ui
    .replace(/__PLUGIN_VERSION__/g, version)
    .split('\n')
    .map((line) => (line.length > 0 ? `    ${line}` : line))
    .join('\n')

  return `${header}\n${body}\n  },\n})\n`
}

const output = build()
const target = path.join(ROOT, 'client.js')
const checkOnly = process.argv.includes('--check')

if (checkOnly) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (current !== output) {
    console.error('client.js is stale: run `node scripts/build-client.mjs`')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  fs.writeFileSync(target, output, 'utf8')
  console.log(`wrote client.js (${output.length} bytes, v${PKG.version})`)
}
